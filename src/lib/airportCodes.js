/**
 * Get display: "George Bush Intercontinental, Houston, US (IAH)"
 */
export function getAirportDisplay(code) {
  if (!code) return '';
  const upper = code.toUpperCase().trim();
  const name = AIRPORT_NAMES[upper];
  return name ? `${name} (${upper})` : upper;
}

/**
 * Get short display for admin: "Houston, US (IAH)"
 */
export function getAirportShort(code) {
  if (!code) return '';
  const upper = code.toUpperCase().trim();
  const name = AIRPORT_NAMES[upper];
  if (!name) return upper;
  // Extract city and country from full name
  const parts = name.split(',').map(s => s.trim());
  if (parts.length >= 3) return `${parts[1]}, ${parts[2]} (${upper})`;
  if (parts.length === 2) return `${parts[1]} (${upper})`;
  return `${name} (${upper})`;
}

export function getAirportName(code) {
  if (!code) return '';
  return AIRPORT_NAMES[code.toUpperCase().trim()] || '';
}

export default AIRPORT_NAMES;
